// A recovery WINDOW may contain 1GiB of source bytes, but the first-window
// streaming loader only holds ONE signed batch in RAM. Preserve the old
// per-batch 256MiB bound independently of the wider window budget.
const backlogStreamBufferedBatchMaxBytes uint64 = 256 << 20

func backlogStreamBatchBufferLimit(windowBytes uint64) uint64 {
	if windowBytes > backlogStreamBufferedBatchMaxBytes {
		return backlogStreamBufferedBatchMaxBytes
	}
	return windowBytes
}

// BacklogStreamProgress reports a successfully inspected batch. It is NOT a
// verified whole generation or an authoritative ingest checkpoint.
type BacklogStreamProgress struct {
	BatchesSeen     uint64
	RecordsSeen     uint64
	DataBytesSeen   uint64
	WindowIndex     int
	RetainedBatches uint64
}

// LoadRecordedGenerationSelectedWindows authenticates and semantically
// validates the ENTIRE original custody transfer in a SINGLE streaming pass,
// while retaining data files ONLY for the requested bounded private windows.
//
// All batch manifest identities (including skipped windows) are held in the
// returned PreparedGeneration so the original signed window-descriptor chain
// can be regenerated byte-for-byte. Skipped batches have empty DataPath and
// MUST NOT be used by the canonical ingester. This is a private recovery
// optimization only; it is NOT an authority to publish.
//
// The handler is invoked before full FIGT transfer verification finishes.
// Consequently no caller may checkpoint a batch until this function returns
// successfully. This version still validates the full transfer before the
// first private transaction; unlike the old loader it never extracts 60+ GiB.
func LoadRecordedGenerationSelectedWindows(
	config GenerationLoadConfig, generationID string,
	limits BacklogWindowLimits, startWindow, maxWindows int,
	progress func(BacklogStreamProgress),
) (*PreparedGeneration, error) {
	return loadRecordedGenerationSelectedWindowsWithTrust(
		config, generationID, limits, startWindow, maxWindows,
		loadInstalledGenerationTrust, progress)
}

// LoadRecordedGenerationSelectedWindowsCached authenticates the full signed
// FIGT once and, after successful transfer verification, publishes all 8,399
// original batches to a shared, receipt-bound read-only benchmark cache.
// Only the requested bounded window is returned to the private ingester.
func LoadRecordedGenerationSelectedWindowsCached(
	config GenerationLoadConfig, generationID string,
	limits BacklogWindowLimits, startWindow, maxWindows int,
	cacheRoot string, progress func(BacklogStreamProgress),
) (*PreparedGeneration,error) {
	return loadRecordedGenerationSelectedWindowsWithTrustAndCache(
		config,generationID,limits,startWindow,maxWindows,cacheRoot,
		loadInstalledGenerationTrust,progress)
}
func loadRecordedGenerationSelectedWindowsWithTrust(
	config GenerationLoadConfig, generationID string,
	limits BacklogWindowLimits, startWindow, maxWindows int,
	resolveTrust generationTrustResolver,
	progress func(BacklogStreamProgress),
) (*PreparedGeneration, error) {
	return loadRecordedGenerationSelectedWindowsWithTrustAndCache(
		config,generationID,limits,startWindow,maxWindows,"",resolveTrust,progress)
}
func loadRecordedGenerationSelectedWindowsWithTrustAndCache(
	config GenerationLoadConfig, generationID string,
	limits BacklogWindowLimits, startWindow, maxWindows int,
	cacheRoot string, resolveTrust generationTrustResolver,
	progress func(BacklogStreamProgress),
) (*PreparedGeneration,error) {
	if err := validateGenerationLoadConfig(config, generationID); err != nil {
		return nil, err
	}
	if resolveTrust == nil {
		return nil, errors.New("FI stream loader: trust resolver required")
	}
	// The current loader retains a bounded set of windows. A separate online
	// projector will later remove the need to select windows in advance.
	if startWindow < 0 || maxWindows < 1 || maxWindows > 8 {
		return nil, errors.New("FI stream loader: nonnegative start and 1..8 selected windows required")
	}
	if limits.MaxRecords == 0 || limits.MaxDataBytes == 0 ||
		limits.MaxDataBytes > 1<<30 || limits.MaxDataBytes > math.MaxInt64-1 {
		return nil, errors.New("FI stream loader: invalid bounded window limits")
	}
	receiptRoot := config.RecordedRoot
	if config.SourceNamespaces {
		var err error
		receiptRoot, err = generationrecorder.RecordedSourceDirectory(receiptRoot, config.SourceID)
		if err != nil {
			return nil, err
		}
	}
	raw, err := readImmutableReceipt(filepath.Join(receiptRoot,
		generationrecorder.RecordedReceiptObjectName(config.SourceID, generationID)))
	if err != nil {
		return nil, fmt.Errorf("FI stream loader: receipt: %w", err)
	}
	receipt, err := generationrecorder.UnmarshalRecordedReceipt(raw)
	if err != nil {
		return nil, err
	}
	if receipt.Descriptor.SourceID != config.SourceID || receipt.Descriptor.GenerationID != generationID {
		return nil, errors.New("FI stream loader: receipt identity conflict")
	}
	receiptSum := sha256.Sum256(raw)
	receiptSHA := hex.EncodeToString(receiptSum[:])
	trust, err := resolveTrust(config.SourceID)
	if err != nil {
		return nil, err
	}
	if !strings.EqualFold(trust.Source.SourceID, config.SourceID) ||
		trust.Root == nil || trust.BatchIssuer == nil || trust.BatchCRL == nil {
		return nil, errors.New("FI stream loader: enrolled signing trust incomplete")
	}

	custodyPath := filepath.Join(config.CustodyRoot,
		transportgeneration.DurableCustodyObjectName(config.SourceID, generationID))
	info, err := os.Lstat(custodyPath)
	if err != nil {
		return nil, err
	}
	if !info.Mode().IsRegular() || info.Mode().Perm() != 0400 || info.Size() <= 0 {
		return nil, errors.New("FI stream loader: immutable custody metadata invalid")
	}
	// The staging directory is temporary; only selected batches are written.
	// Use the existing stage lease and cleanup semantics from the trusted loader.
	stageDir, err := os.MkdirTemp("", "fi-relational-stream-generation-*")
	if err != nil {
		return nil, err
	}
	lease, err := newGenerationStageLease(stageDir)
	if err != nil {
		_ = os.RemoveAll(stageDir)
		return nil, err
	}
	keep := false
	cacheStaging:=""
	if cacheRoot!="" {
		cacheStaging,err=backlogVerifiedCacheBegin(cacheRoot,receiptSHA)
		if err!=nil{return nil,fmt.Errorf("FI stream cache: preflight: %w",err)}
	}
	defer func(){
		if cacheStaging!=""{_ = os.RemoveAll(cacheStaging)}
	}()
	defer func() {
		if !keep {
			_ = removeGenerationStageDirectory(stageDir)
			_ = lease.Close()
		}
	}()

	var batches []PreparedBatch
	var recordsSeen, dataSeen uint64
	var retained uint64
	currentWindow, currentRecords, currentBytes := 0, uint64(0), uint64(0)
	var pendingName string
	var pendingInspection spool.DataInspection
	var buffer bytes.Buffer
	batchBufferMax := backlogStreamBatchBufferLimit(limits.MaxDataBytes)
	// Streaming artifact names are ordered as data,manifest pairs by the
	// canonical transport framing. Reject any unexpected order or filename.
	factory := func(desc transportgeneration.Descriptor) (transportgeneration.CanonicalArtifactHandler, error) {
		if desc != receipt.Descriptor {
			return nil, errors.New("FI stream loader: signed descriptor changed")
		}
		return func(name string, reader io.Reader) error {
			if filepath.Base(name) != name || strings.ContainsAny(name, "/\\") {
				return errors.New("FI stream loader: unsafe artifact filename")
			}
			if pendingName == "" {
				if !strings.HasPrefix(name, "batch-") || !strings.HasSuffix(name, ".jsonl") {
					return fmt.Errorf("FI stream loader: expected batch data, got %q", name)
				}
				buffer.Reset()
				// A bounded in-memory buffer avoids writing and deleting 60 GiB
				// of unrelated source data just to discover window boundaries.
				inspection, err := spool.InspectData(io.TeeReader(
					io.LimitReader(reader, int64(batchBufferMax)+1), &buffer))
				if err != nil {
					return fmt.Errorf("FI stream loader: inspect %s: %w", name, err)
				}
				if inspection.DataBytes <= 0 || uint64(inspection.DataBytes) > batchBufferMax ||
					int64(buffer.Len()) != inspection.DataBytes {
					return errors.New("FI stream loader: batch data exceeds bounded memory budget")
				}
				pendingName = name
				pendingInspection = inspection
				return nil
			}
			batchID := strings.TrimSuffix(strings.TrimPrefix(pendingName, "batch-"), ".jsonl")
			if batchID == "" || name != "batch-"+batchID+".manifest.json" {
				return fmt.Errorf("FI stream loader: data/manifest pair mismatch %q %q", pendingName, name)
			}
			manifestRaw, err := io.ReadAll(io.LimitReader(reader, int64(config.MaxManifestBytes)+1))
			if err != nil {
				return err
			}
			if len(manifestRaw) == 0 || uint64(len(manifestRaw)) > config.MaxManifestBytes {
				return errors.New("FI stream loader: manifest bytes outside bound")
			}
			m, err := spool.DecodeManifest(bytes.NewReader(manifestRaw))
			if err != nil {
				return err
			}
			if m.BatchID != batchID || m.DataFile != pendingName {
				return errors.New("FI stream loader: signed batch manifest identity mismatch")
			}
			if err := spool.VerifyManifestData(m, pendingInspection); err != nil {
				return err
			}
			if m.RecordCount <= 0 || uint64(m.RecordCount) > limits.MaxRecords ||
				m.DataBytes <= 0 || uint64(m.DataBytes) > limits.MaxDataBytes {
				return errors.New("FI stream loader: intact batch exceeds window limits")
			}
			if len(batches) > 0 && batchID <= batches[len(batches)-1].BatchID {
				return errors.New("FI stream loader: duplicate/out-of-order batch")
			}
			n := uint64(m.RecordCount)
			b := uint64(m.DataBytes)
			if currentRecords > 0 &&
				(n > limits.MaxRecords-currentRecords ||
					b > limits.MaxDataBytes-currentBytes) {
				currentWindow++
				currentRecords = 0
				currentBytes = 0
			}
			keepBatch := currentWindow >= startWindow && currentWindow < startWindow+maxWindows
			var dataPath string
			if keepBatch {
				dataPath = filepath.Join(stageDir, fmt.Sprintf("batch-%08d.data", len(batches)))
				f, err := os.OpenFile(dataPath, os.O_CREATE|os.O_EXCL|os.O_WRONLY, 0600)
				if err != nil {
					return err
				}
				written, writeErr := f.Write(buffer.Bytes())
				if writeErr == nil && written != buffer.Len() {
					writeErr = io.ErrShortWrite
				}
				writeErr = errors.Join(writeErr, f.Close())
				if writeErr != nil {
					return writeErr
				}
				retained++
			}
			// Cache only manifests that matched their inspected data bytes,
			// signing metadata and canonical batch order. These remain
			// provisional until the WHOLE signed FIGT verifies at EOF.
			if cacheStaging!=""{
				index:=len(batches)
				if err:=writeBacklogStageFile(backlogCacheBatchData(cacheStaging,index),buffer.Bytes());err!=nil{
					return fmt.Errorf("FI verified cache: data batch %d: %w",index,err)
				}
				if err:=writeBacklogStageFile(backlogCacheBatchManifest(cacheStaging,index),manifestRaw);err!=nil{
					return fmt.Errorf("FI verified cache: manifest batch %d: %w",index,err)
				}
			}
			hash := sha256.Sum256(manifestRaw)
			batches = append(batches, PreparedBatch{
				BatchID: batchID, DataArtifactName: pendingName, DataPath: dataPath,
				Manifest: m, ManifestArtifactName: name, ManifestBytes: len(manifestRaw),
				ManifestRawBytes: manifestRaw, ManifestSHA256: hex.EncodeToString(hash[:]),
			})
			if n > math.MaxUint64-recordsSeen || b > math.MaxUint64-dataSeen {
				return errors.New("FI stream loader: generation count overflow")
			}
			recordsSeen += n
			dataSeen += b
			currentRecords += n
			currentBytes += b
			pendingName = ""
			if progress != nil {
				progress(BacklogStreamProgress{
					BatchesSeen: uint64(len(batches)), RecordsSeen: recordsSeen,
					DataBytesSeen: dataSeen, WindowIndex: currentWindow,
					RetainedBatches: retained,
				})
			}
			return nil
		}, nil
	}
	result, err := transportgeneration.ReadDiscoveredDurableCustodyArtifacts(
		transportgeneration.DiscoveredCustody{Path: custodyPath, Bytes: uint64(info.Size())},
		transportgeneration.CustodyConfig{
			RootDir: config.CustodyRoot,
			Receive: transportgeneration.ReceiveConfig{
				BatchCRL: trust.BatchCRL, BatchIssuer: trust.BatchIssuer,
				CurrentTime: time.Now(), MaxCanonicalBytes: config.MaxCanonicalBytes,
				MaxEncodedBytes: config.MaxEncodedBytes, Root: trust.Root, Source: trust.Source,
			},
		}, factory)
	if err != nil {
		return nil, fmt.Errorf("FI stream loader: authenticated custody: %w", err)
	}
	if pendingName != "" {
		return nil, errors.New("FI stream loader: dangling unmatched batch data")
	}
	transfer := result.Transfer
	if transfer.Descriptor != receipt.Descriptor ||
		transfer.MetadataBytes != receipt.MetadataBytes ||
		transfer.MetadataSHA256 != receipt.MetadataSHA256 ||
		transfer.TransferBytes != receipt.TransferBytes ||
		transfer.TransferSHA256 != receipt.TransferSHA256 {
		return nil, errors.New("FI stream loader: signed custody differs from immutable recorded receipt")
	}
	if uint64(len(batches)) != receipt.BatchCount || recordsSeen != receipt.RecordCount ||
		dataSeen != receipt.DataBytes {
		return nil, fmt.Errorf("FI stream loader: generation totals mismatch batches=%d/%d records=%d/%d bytes=%d/%d",
			len(batches), receipt.BatchCount, recordsSeen, receipt.RecordCount, dataSeen, receipt.DataBytes)
	}
	if retained == 0 {
		return nil, errors.New("FI stream loader: selected window range contains no batches")
	}
	gen := &PreparedGeneration{
		Batches: batches, Receipt: receipt, ReceiptBytes: len(raw),
		ReceiptRawBytes: append([]byte(nil), raw...), ReceiptSHA256: receiptSHA,
		stagedDirectory: stageDir, stageLease: lease,
	}
	descs, err := DescribeBacklogWindows(gen, limits)
	if err != nil {
		return nil, fmt.Errorf("FI stream loader: full signed window plan: %w", err)
	}
	if startWindow >= len(descs) || startWindow+maxWindows > len(descs) {
		return nil, fmt.Errorf("FI stream loader: requested [%d,%d) windows outside [0,%d)",
			startWindow, startWindow+maxWindows, len(descs))
	}
	// Cross-check the online partition with the independently computed
	// canonical full-generation plan before returning any usable staged data.
	if currentWindow+1 != len(descs) {
		return nil, errors.New("FI stream loader: online window partition differs from signed plan")
	}
	for i := range batches {
		selected := false
		for w := startWindow; w < startWindow+maxWindows; w++ {
			if i >= descs[w].StartBatch && i < descs[w].EndBatch {
				selected = true
				break
			}
		}
		if selected != (batches[i].DataPath != "") {
			return nil, fmt.Errorf("FI stream loader: retained batch selection mismatch at %d", i)
		}
	}
	if cacheStaging!=""{
		if err:=backlogVerifiedCacheCommit(cacheRoot,cacheStaging,receiptSHA,
			receipt.TransferSHA256,receipt.BatchCount,receipt.RecordCount,receipt.DataBytes);err!=nil{
			return nil,fmt.Errorf("FI verified cache: publish complete authenticated dataset: %w",err)
		}
		cacheStaging=""
	}
	keep = true
	return gen, nil
}
